#!/usr/bin/env python3
"""Generate MySQL 8 DDL from the agreed field document (扫描工程数据库字段说明.md).

The service never executes DDL; the output is for reviewed deployment and the
isolated test database. Differences against llm_detect.v21.contract are
reported so the document and the read-only schema check cannot drift silently.
"""
import argparse
import re
import sys
from pathlib import Path

SERVICE_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(SERVICE_ROOT))

TABLE = re.compile(r"^### \d+\.\d+ `(\w+)`[：:](.*)$")
FIELD = re.compile(r"^\| `(\w+)` \| ([^|]+?) \| ([^|]+?) \| (.*)\|\s*$")
INDEX = re.compile(r"`((?:idx|uk)_\w+)\(([^)]*)\)`")
NUMERIC = re.compile(r"-?\d+(?:\.\d+)?")


def quote(text):
    return "'" + text.replace("\\", "\\\\").replace("'", "''") + "'"


def parse(document):
    tables, current = {}, None
    for line in document.read_text(encoding="utf-8").splitlines():
        match = TABLE.match(line)
        if match:
            current = {"comment": match.group(2).strip(), "columns": {}, "indexes": {}}
            tables[match.group(1)] = current
            continue
        if current is None:
            continue
        match = FIELD.match(line)
        if match:
            name, kind, rule, note = (part.strip() for part in match.groups())
            parts = [p.strip() for p in rule.split("、")]
            default = None
            for part in parts[1:]:
                if part not in {"AUTO_INCREMENT", "DEFAULT NULL"}:
                    default = part
            current["columns"][name] = {"type": kind, "required": parts[0] == "必填", "default": default, "note": note}
            continue
        if line.startswith("- "):
            for index, columns in INDEX.findall(line):
                unique = index.startswith("uk_") or "唯一键" in line
                current["indexes"][index] = {"unique": unique, "columns": [c.strip() for c in columns.split(",")]}
    return {name: spec for name, spec in tables.items() if spec["columns"]}


def column_sql(name, spec, warnings, table):
    if name == "id":
        return f"  `id` {spec['type']} NOT NULL AUTO_INCREMENT COMMENT {quote(spec['note'])}"
    sql = f"  `{name}` {spec['type']}" + (" NOT NULL" if spec["required"] else " NULL")
    default = spec["default"]
    if default is not None:
        if spec["type"].upper().endswith("TEXT"):
            pass  # TEXT defaults are application-initialised per §1.2.
        elif NUMERIC.fullmatch(default):
            sql += f" DEFAULT {default}"
        elif re.fullmatch(r"[A-Za-z0-9_]+", default):
            sql += f" DEFAULT {quote(default)}"
        else:
            warnings.append(f"{table}.{name}: default {default!r} not applied")
    elif not spec["required"]:
        sql += " DEFAULT NULL"
    return sql + f" COMMENT {quote(spec['note'])}"


def build(tables):
    warnings, out = [], ["-- Generated by deploy/build_schema_sql.py from 扫描工程数据库字段说明.md. Review before applying.",
                         "-- MySQL 8 / InnoDB / utf8mb4. All business times are stored in UTC.", ""]
    for table, spec in tables.items():
        lines = [column_sql(name, column, warnings, table) for name, column in spec["columns"].items()]
        lines.append("  PRIMARY KEY (`id`)")
        for index, info in spec["indexes"].items():
            missing = [c for c in info["columns"] if c not in spec["columns"]]
            if missing:
                warnings.append(f"{table}.{index}: unknown columns {missing}")
                continue
            columns = ", ".join(f"`{c}`" for c in info["columns"])
            lines.append(f"  {'UNIQUE KEY' if info['unique'] else 'KEY'} `{index}` ({columns})")
        out.append(f"CREATE TABLE IF NOT EXISTS `{table}` (\n" + ",\n".join(lines) +
                   f"\n) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT={quote(spec['comment'])};\n")
    return "\n".join(out), warnings


def compare(tables):
    from llm_detect.v21.contract import CONTRACT
    from llm_detect.v21.indexes import UNIQUE_INDEXES
    issues = []
    for table, columns in CONTRACT.items():
        doc = tables.get(table)
        if doc is None:
            issues.append(f"{table}: in contract but not in document")
            continue
        for name, spec in columns.items():
            other = doc["columns"].get(name)
            if other is None:
                issues.append(f"{table}.{name}: in contract but not in document")
            elif (other["type"].upper(), other["required"]) != (spec["type"].upper(), spec["required"]):
                issues.append(f"{table}.{name}: document {other['type']}/{other['required']} vs contract {spec['type']}/{spec['required']}")
        for name in set(doc["columns"]) - set(columns):
            issues.append(f"{table}.{name}: in document but not in contract")
    for table, indexes in UNIQUE_INDEXES.items():
        for name, columns in indexes.items():
            info = tables.get(table, {}).get("indexes", {}).get(name)
            if not info or not info["unique"] or info["columns"] != columns:
                issues.append(f"{table}.{name}: unique key differs from document")
    return issues


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("document", type=Path)
    parser.add_argument("--output", type=Path, default=SERVICE_ROOT / "deploy" / "schema_v21_mysql.sql")
    args = parser.parse_args()
    tables = parse(args.document)
    sql, warnings = build(tables)
    issues = compare(tables)
    args.output.write_text(sql, encoding="utf-8", newline="\n")
    indexes = sum(len(t["indexes"]) for t in tables.values())
    print(f"tables={len(tables)} columns={sum(len(t['columns']) for t in tables.values())} indexes={indexes} -> {args.output}")
    for line in warnings + issues:
        print("WARN", line)
    return 1 if issues else 0


if __name__ == "__main__":
    raise SystemExit(main())
